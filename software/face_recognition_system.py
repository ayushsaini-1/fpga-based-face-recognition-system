#!/usr/bin/env python3
"""Camera-based face enrollment and recognition with FPGA-compatible preprocessing."""
from __future__ import annotations

import argparse
import pickle
from pathlib import Path
from typing import Dict, List, Tuple

import cv2
import face_recognition
import numpy as np


class FaceRecognitionSystem:
    def __init__(self, database: Path, tolerance: float = 0.48) -> None:
        self.database = database
        self.tolerance = tolerance
        self.known: Dict[str, List[np.ndarray]] = {}
        if database.exists():
            with database.open("rb") as handle:
                self.known = pickle.load(handle)

    def save(self) -> None:
        self.database.parent.mkdir(parents=True, exist_ok=True)
        with self.database.open("wb") as handle:
            pickle.dump(self.known, handle)

    @staticmethod
    def preprocess(frame: np.ndarray) -> np.ndarray:
        """Match the FPGA front-end: grayscale, contrast normalization, resize."""
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        gray = cv2.equalizeHist(gray)
        return cv2.resize(gray, (320, 240), interpolation=cv2.INTER_AREA)

    def enroll(self, name: str, image_path: Path) -> int:
        image = face_recognition.load_image_file(image_path)
        locations = face_recognition.face_locations(image, model="hog")
        encodings = face_recognition.face_encodings(image, locations)
        if not encodings:
            raise ValueError(f"No face found in {image_path}")
        self.known.setdefault(name, []).extend(encodings)
        self.save()
        return len(encodings)

    def recognize(self, frame: np.ndarray) -> List[Tuple[str, Tuple[int, int, int, int], float]]:
        # The normalized frame can be generated by the FPGA and supplied here.
        _ = self.preprocess(frame)
        rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        locations = face_recognition.face_locations(rgb, model="hog")
        encodings = face_recognition.face_encodings(rgb, locations)
        known_names = list(self.known)
        known_vectors = [vector for name in known_names for vector in self.known[name]]
        results = []
        for encoding, location in zip(encodings, locations):
            name, distance = "Unknown", 1.0
            if known_vectors:
                distances = face_recognition.face_distance(known_vectors, encoding)
                index = int(np.argmin(distances))
                if distances[index] <= self.tolerance:
                    name = known_names[next(i for i, n in enumerate(known_names) if index < len(self.known[n]))]
                    remaining = index
                    for candidate in known_names:
                        if remaining < len(self.known[candidate]):
                            name = candidate
                            break
                        remaining -= len(self.known[candidate])
                distance = float(distances[index])
            results.append((name, location, distance))
        return results

    def run_camera(self, camera: int = 0) -> None:
        capture = cv2.VideoCapture(camera)
        if not capture.isOpened():
            raise RuntimeError(f"Cannot open camera {camera}")
        while True:
            ok, frame = capture.read()
            if not ok:
                raise RuntimeError("Camera frame could not be read")
            for name, (top, right, bottom, left), distance in self.recognize(frame):
                cv2.rectangle(frame, (left, top), (right, bottom), (0, 200, 0), 2)
                cv2.putText(frame, f"{name} ({distance:.2f})", (left, max(20, top - 8)),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.65, (0, 200, 0), 2)
            cv2.imshow("FPGA Face Recognition", frame)
            if cv2.waitKey(1) & 0xFF == ord("q"):
                break
        capture.release()
        cv2.destroyAllWindows()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", type=Path, default=Path("data/encodings.pkl"))
    sub = parser.add_subparsers(dest="command", required=True)
    enroll = sub.add_parser("enroll")
    enroll.add_argument("name")
    enroll.add_argument("image", type=Path)
    run = sub.add_parser("run")
    run.add_argument("--camera", type=int, default=0)
    args = parser.parse_args()
    system = FaceRecognitionSystem(args.database)
    if args.command == "enroll":
        print(f"Enrolled {system.enroll(args.name, args.image)} face(s) for {args.name}.")
    else:
        system.run_camera(args.camera)


if __name__ == "__main__":
    main()
